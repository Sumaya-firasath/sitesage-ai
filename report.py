"""report.py - builds the downloadable PDF report with ReportLab."""
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from auditor import score_color

STATUS_COLORS = {"pass": "#16A34A", "warning": "#D97706", "fail": "#DC2626", "info": "#2563EB"}


def safe(text) -> str:
    """Escape XML characters; the built-in PDF font only supports Latin characters."""
    return escape(str(text).encode("latin-1", "replace").decode("latin-1"))


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#64748B"))
    canvas.drawString(18 * mm, 10 * mm, "Generated by SiteSage AI - single-page, rule-based SEO audit")
    canvas.drawRightString(192 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_pdf(result) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=18 * mm, title="SiteSage AI SEO Audit Report")
    base = getSampleStyleSheet()
    title = ParagraphStyle("t", parent=base["Title"], alignment=0, fontSize=22, textColor=colors.HexColor("#4F46E5"))
    h2 = ParagraphStyle("h2", parent=base["Heading2"], textColor=colors.HexColor("#0F172A"), spaceBefore=12)
    body = ParagraphStyle("b", parent=base["BodyText"], fontSize=10, leading=14)
    cell = ParagraphStyle("c", parent=base["BodyText"], fontSize=8.5, leading=11)
    head = ParagraphStyle("hd", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")

    story = [
        Paragraph("SiteSage AI - SEO Audit Report", title),
        Paragraph(f"<b>URL audited:</b> {safe(result.final_url)}", body),
        Paragraph(f"<b>Date:</b> {result.audited_at:%d %b %Y, %H:%M}", body),
        Spacer(1, 8),
    ]

    col = score_color(result.score)
    summary = Table([
        [Paragraph(f'<font size="26" color="{col}"><b>{result.score}</b></font><font size="12"> / 100</font>', body),
         Paragraph(f"<b>{safe(result.grade)}</b><br/>{result.count('pass')} passed, "
                   f"{result.count('warning')} warnings, {result.count('fail')} failed", body)]
    ], colWidths=[50 * mm, 124 * mm])
    summary.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#E2E8F0")),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 10), ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
    ]))
    story += [summary, Paragraph("Audit checks", h2)]

    rows = [[Paragraph(h, head) for h in ("Status", "Check", "Finding", "Points")]]
    for c in result.checks:
        color = STATUS_COLORS[c.status]
        pts = "-" if c.status == "info" else f"{c.earned:g}/{c.weight}"
        rows.append([Paragraph(f'<font color="{color}"><b>{c.status.upper()}</b></font>', cell),
                     Paragraph(safe(c.name), cell), Paragraph(safe(c.finding), cell), Paragraph(pts, cell)])
    table = Table(rows, colWidths=[20 * mm, 34 * mm, 100 * mm, 20 * mm], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4F46E5")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E2E8F0")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story += [table, Paragraph("Priority recommendations", h2)]

    todo = [c for c in result.checks if c.status == "fail"] + [c for c in result.checks if c.status == "warning"]
    if todo:
        for i, c in enumerate(todo, 1):
            story.append(Paragraph(f"<b>{i}. {safe(c.name)}</b> ({c.status.upper()}): {safe(c.recommendation)}", body))
            story.append(Spacer(1, 3))
    else:
        story.append(Paragraph("All scored checks passed. No fixes needed.", body))

    story += [Paragraph("Scope and limits", h2), Paragraph(
        "This report analyses the HTML of one page fetched at the time shown above. Score = points earned / "
        "points available across the checks that were scored (pass = full points, warning = half, fail = zero). "
        "It does not measure Google rankings, traffic, backlinks or Core Web Vitals, and it does not run "
        "JavaScript, so content added by scripts is not seen.", body)]

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
